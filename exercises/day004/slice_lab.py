# slice_lab.py - 下标与切片练习

scores = [68, 75, 82, 90, 96]
# 下标：   0   1   2   3   4
# 负下标： -5  -4  -3  -2  -1

print("第一个成绩：", scores[0])       # 第一个永远是0号位
print("最后一个成绩：", scores[-1])     # 负下标：-1 = 倒数第一个

print("前三个成绩：", scores[0:3])      # 左闭右开：取到0、1、2
print("后三个成绩：", scores[2:5])      # 取到2、3、4
print("中间三个成绩：", scores[1:4])    # 取到1、2、3